import { User } from '../models/index.js';

export const findUserWithPolicies = async (firstName) => {
  // Use aggregation to perform SQL-like left joins across collections
  const pipeline = [
    {
      $match: {
        firstName: { $regex: new RegExp(firstName, 'i') }, // Case-insensitive search
      },
    },
    {
      $lookup: {
        from: 'policies', // Mongoose automatically lowercases and pluralizes collection names
        localField: '_id',
        foreignField: 'userId',
        as: 'policies',
      },
    },
    {
      $unwind: {
        path: '$policies',
        preserveNullAndEmptyArrays: true, // Keep users even if they have no policies yet
      },
    },
    {
      $lookup: {
        from: 'policycategories',
        localField: 'policies.policyCategoryId',
        foreignField: '_id',
        as: 'policies.category',
      },
    },
    {
      $lookup: {
        from: 'policycarriers',
        localField: 'policies.companyId',
        foreignField: '_id',
        as: 'policies.carrier',
      },
    },
    {
      // Flatten the nested arrays generated by $lookup for cleaner JSON output
      $addFields: {
        'policies.category': { $arrayElemAt: ['$policies.category', 0] },
        'policies.carrier': { $arrayElemAt: ['$policies.carrier', 0] },
      },
    },
    {
      // Group back by user ID to merge policies into an array
      $group: {
        _id: '$_id',
        firstName: { $first: '$firstName' },
        email: { $first: '$email' },
        phoneNumber: { $first: '$phoneNumber' },
        policies: { $push: '$policies' },
      },
    },
  ];

  return await User.aggregate(pipeline);
};